const LanguageContext = createContext();

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    try {
      const saved = localStorage.getItem('nandankanan_lang');
      if (saved && ['en', 'or', 'hi', 'bn'].includes(saved)) {
        return saved;
      }
    } catch (e) {
      // Ignore
    }
    return 'en';
  });

  const setLanguage = (lang) => {
    if (['en', 'or', 'hi', 'bn'].includes(lang)) {
      setLanguageState(lang);
      try {
        localStorage.setItem('nandankanan_lang', lang);
      } catch (e) {
        // Ignore
      }
    }
  };

  const t = (path) => {
    if (!path) return '';
    const keys = path.split('.');
    let cur = TRANSLATIONS[language];
    for (const k of keys) {
      if (cur && cur[k] !== undefined) {
        cur = cur[k];
      } else {
        // Fallback to English
        let fallback = TRANSLATIONS.en;
        for (const fk of keys) {
          if (fallback && fallback[fk] !== undefined) {
            fallback = fallback[fk];
          } else {
            return path;
          }
        }
        return fallback;
      }
    }
    return cur;
  };

  const getAnimalName = (animal) => {
    if (!animal) return '';
    const slug = animal.slug || (animal.name ? animal.name.toLowerCase().replace(/\s+/g, '-') : '');
    if (ANIMAL_TRANSLATIONS[slug] && ANIMAL_TRANSLATIONS[slug][language]) {
      return ANIMAL_TRANSLATIONS[slug][language];
    }
    return animal.name || '';
  };

  const currentLanguageMeta = LANGUAGES.find((l) => l.code === language) || LANGUAGES[0];

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage,
        t,
        getAnimalName,
        currentLanguageMeta,
        languages: LANGUAGES,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
